import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createJourneyCycle, appendJourneyCheckIn, reassessJourneyCycle,
  auditJourneyEvidence, isJourneyCycle } from '../src/lib/closedLoopJourney.ts';
import { runSyntheticGoldenPath, createEnvelope, verifyEnvelope } from '../tools/cla_golden_path_offline.mjs';
import { fingerprint } from '../tools/cp31_release_fingerprint.cjs';
