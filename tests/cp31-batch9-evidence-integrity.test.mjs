const fixtureText = readFileSync(new URL('../research/golden_path/fixture_SYNTHETIC.v1.json', import.meta.url), 'utf8');
const fixture = JSON.parse(fixtureText);
const clone = x => structuredClone(x);
const plan = () => createJourneyCycle(fixture.cycle);
function reviewed() {
  let cycle = plan();
  for (const c of fixture.checkIns) cycle = appendJourneyCheckIn(cycle, c);
  return reassessJourneyCycle(cycle, fixture.reassessment);
}
const mutation = (fn, expected = 'MISMATCH') => {
  const cycle = reviewed(); fn(cycle);
  assert.equal(auditJourneyEvidence(cycle), expected);
  assert.equal(isJourneyCycle(cycle), false);
};

test('B9-01 audited reviewed evidence generated by domain engine is consistent', () => {
  assert.equal(auditJourneyEvidence(reviewed()), 'CONSISTENT');
  assert.equal(isJourneyCycle(reviewed()), true);
});
test('B9-02 preserved 0 score and 0 check-in count are observed values', () => {
  const c=reviewed(); assert.equal(c.subjects[0].baseline,0);
  assert.equal(c.reassessment.observations[0].score,0);
  assert.equal(c.checkIns[0].actualHours,0);
  assert.equal(c.checkIns[0].completedActions,0);
  assert.equal(auditJourneyEvidence(c),'CONSISTENT');
});
test('B9-03 Firestore-like reordering of map keys is semantically identical',()=>{
  const c=reviewed();
  const backwards = o => Object.fromEntries(Object.entries(o).reverse());
  c.evidenceRecord = backwards(c.evidenceRecord);
  c.evidenceRecord.output = backwards(c.evidenceRecord.output);
  c.evidenceRecord.engine = backwards(c.evidenceRecord.engine);
  assert.equal(auditJourneyEvidence(c),'CONSISTENT');
});
test('B9-04 reviewed legacy records with no evidence remain readable, never PASS',()=>{
  const c=reviewed(); delete c.evidenceRecord;
  assert.equal(auditJourneyEvidence(c),'LEGACY_NO_EVIDENCE');
  assert.equal(isJourneyCycle(c),true);
});
test('B9-05 explicit null legacy remains readable',()=>{
  const c=reviewed(); c.evidenceRecord=null;
  assert.equal(auditJourneyEvidence(c),'LEGACY_NO_EVIDENCE');
  assert.equal(isJourneyCycle(c),true);
});
test('B9-06 active plan cannot claim reviewed lineage',()=>{
  assert.equal(auditJourneyEvidence(plan()),'NOT_REVIEWED');
  assert.equal(isJourneyCycle(plan()),true);
  const c=plan();c.evidenceRecord=reviewed().evidenceRecord;
  assert.equal(isJourneyCycle(c),false);
});
