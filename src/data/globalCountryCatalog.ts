export function findCountry(code: string): CountryEntry | undefined {
  return countryCatalog.find(entry => entry.code === code);
}
export function searchCountries(value: string): CountryEntry[] {
  const needle = value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/đ/g, "d").toLowerCase().trim();
  if (!needle) return countryCatalog;
  return countryCatalog.filter(item =>
    `${item.name} ${item.englishName} ${item.code}`.normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "").replace(/đ/g, "d").toLowerCase().includes(needle)
  );
}
