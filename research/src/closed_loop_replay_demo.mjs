#!/usr/bin/env node
/**
 * Synthetic technical replay of the CLA closed-loop target architecture.
 * Uses the current Orion strategy engine, but all learner-like inputs and
 * the outcome are generated demo fixtures. It is NOT a real student trace,
 * NOT persisted to Firestore, and NOT evidence of learning effectiveness.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { runOrionStrategy } from '../../src/lib/orionStrategyEngine.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const ENGINE_PATH = resolve(ROOT, 'src/lib/orionStrategyEngine.ts');
const ENGINE_SHA256 = createHash('sha256').update(readFileSync(ENGINE_PATH)).digest('hex');
const CHECKED_AT = '2026-11-09T00:00:00.000Z';

function makeSubjects(mathScore) {
  return [
    { subject: 'math', label: 'Toán', currentScore: mathScore, targetScore: 8.2, importance: 1.3 },
    { subject: 'english', label: 'Tiếng Anh', currentScore: 7.6, targetScore: 8.0, importance: 1.0 },
    { subject: 'physics', label: 'Vật lý', currentScore: 6.9, targetScore: 7.8, importance: 1.2 },
  ];
}

function assertTrace(trace) {
  const expected = [
    'snapshot', 'assessment', 'recommendation', 'intervention_plan',
    'check_in', 'outcome', 'reassessment', 'adaptation',
  ];
  const actual = trace.stages.map(stage => stage.name);
  if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('Closed-loop stage order invalid');
  if (trace.dataScope !== 'synthetic' || trace.evidenceClass !== 'S') throw new Error('Synthetic evidence label missing');
  if (trace.empiricalClaimEligible !== false || trace.complete !== false) throw new Error('Demo must not be marked empirical or complete');
  const ids = new Set(trace.stages.map(stage => stage.id));
  if (ids.size !== expected.length) throw new Error('Duplicate stage IDs');
  for (const stage of trace.stages) {
    for (const ref of stage.dependsOn) if (!ids.has(ref)) throw new Error(`Unknown stage reference: ${ref}`);
  }
  if (trace.stages.find(stage => stage.name === 'outcome')?.status !== 'SIMULATED_NOT_OBSERVED') {
    throw new Error('Demo outcome must be labelled simulated, not observed');
  }
  return true;
}

export function runClosedLoopReplayDemo() {
  const initial = runOrionStrategy({
    subjects: makeSubjects(6.8),
    weeksLeft: 8,
    targetMajor: 'Khoa học dữ liệu',
  });
  const chosen = initial.bestScenario;
  const actionStatuses = [true, true, false, true];
  const completed = actionStatuses.filter(Boolean).length;
  const adherenceRate = completed / actionStatuses.length;
  // The following value is deliberately generated by a transparent demo rule.
  const simulatedDelta = Number((adherenceRate * 0.4).toFixed(2));
  const simulatedScore = Number((6.8 + simulatedDelta).toFixed(2));
  const reassessed = runOrionStrategy({
    subjects: makeSubjects(simulatedScore),
    weeksLeft: 7,
    targetMajor: 'Khoa học dữ liệu',
  });
  const belowAdherenceThreshold = adherenceRate < 0.8;
  const adaptedScenario = belowAdherenceThreshold ? 'balanced' : reassessed.bestScenario.id;
  const adaptedWeeklyHours = belowAdherenceThreshold
    ? Math.max(6, chosen.weeklyHours - 2)
    : reassessed.bestScenario.weeklyHours;

  const stages = [
    { name: 'snapshot', id: 'SYN-SNAPSHOT-001', status: 'SYNTHETIC_INPUT', dependsOn: [], payload: { currentScores: { math: 6.8, english: 7.6, physics: 6.9 }, targetMajor: 'Khoa học dữ liệu', weeksLeft: 8 } },
    { name: 'assessment', id: 'SYN-ASSESSMENT-001', status: 'RULE_BASED_ASSESSMENT', dependsOn: ['SYN-SNAPSHOT-001'], payload: { overallGap: initial.overallGap, readinessScore: initial.readinessScore, riskLevel: initial.riskLevel, formulaEngine: 'orion-strategy-engine', engineSha256: ENGINE_SHA256 } },
    { name: 'recommendation', id: 'SYN-RECOMMENDATION-001', status: 'ENGINE_OUTPUT', dependsOn: ['SYN-SNAPSHOT-001', 'SYN-ASSESSMENT-001'], payload: { scenarioId: chosen.id, title: chosen.title, riskLevel: chosen.riskLevel, expectedGain: chosen.expectedGain, weeklyHours: chosen.weeklyHours, focusSubjects: chosen.focusSubjects } },
    { name: 'intervention_plan', id: 'SYN-PLAN-001', status: 'DEMO_PLAN_CREATED', dependsOn: ['SYN-RECOMMENDATION-001'], payload: { durationWeeks: 1, actions: initial.milestones[0].actions, weeklyHours: chosen.weeklyHours, humanOverrideAllowed: true } },
    { name: 'check_in', id: 'SYN-CHECKIN-001', status: 'SYNTHETIC_CHECKIN', dependsOn: ['SYN-PLAN-001'], payload: { actionStatuses, completedActions: completed, totalActions: actionStatuses.length, adherenceRate } },
    { name: 'outcome', id: 'SYN-OUTCOME-001', status: 'SIMULATED_NOT_OBSERVED', dependsOn: ['SYN-CHECKIN-001', 'SYN-SNAPSHOT-001'], payload: { baselineScore: 6.8, simulatedDelta, simulatedScore, generationRule: 'adherenceRate * 0.4', isRealObservation: false } },
    { name: 'reassessment', id: 'SYN-REASSESSMENT-001', status: 'RULE_BASED_REASSESSMENT', dependsOn: ['SYN-OUTCOME-001'], payload: { updatedMathScore: simulatedScore, overallGap: reassessed.overallGap, readinessScore: reassessed.readinessScore, riskLevel: reassessed.riskLevel, engineSha256: ENGINE_SHA256 } },
    { name: 'adaptation', id: 'SYN-ADAPTATION-001', status: 'DEMO_POLICY_ADAPTATION', dependsOn: ['SYN-CHECKIN-001', 'SYN-REASSESSMENT-001'], payload: { trigger: 'adherenceRate < 0.8', triggered: belowAdherenceThreshold, selectedScenarioId: adaptedScenario, adaptedWeeklyHours, rationale: belowAdherenceThreshold ? 'Giảm tải và chia nhỏ nhiệm vụ do mức hoàn thành demo dưới ngưỡng 80%.' : 'Giữ chiến lược sau đánh giá lại.', thresholdIsDemoOnly: true } },
  ];

  const trace = {
    traceId: 'CLA-SYNTHETIC-CLOSED-LOOP-001',
    protocolVersion: 'cla-closed-loop-demo-v1',
    createdAt: CHECKED_AT,
    dataScope: 'synthetic',
    evidenceClass: 'S',
    empiricalClaimEligible: false,
    complete: false,
    engine: { name: 'runOrionStrategy', sourceFile: 'src/lib/orionStrategyEngine.ts', sha256: ENGINE_SHA256 },
    stages,
    limitations: [
      'All learner-like inputs and check-in states are synthetic fixtures.',
      'Outcome value is generated by a deterministic demo rule; it is not an observed student outcome.',
      'This replay is not persisted to Firestore and is not integrated with the live Student UI.',
      'The 80% adaptation threshold is a demonstration constant, not a validated intervention threshold.',
      'No causal, psychometric, ML or learning-effectiveness claim is supported.',
    ],
  };
  assertTrace(trace);
  return trace;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = resolve(ROOT, 'research/evidence/closed_loop_demo_trace.json');
  mkdirSync(dirname(output), { recursive: true });
  const trace = runClosedLoopReplayDemo();
  writeFileSync(output, `${JSON.stringify(trace, null, 2)}\n`, 'utf8');
  process.stdout.write(`CLOSED_LOOP_SYNTHETIC_REPLAY_PASS stages=${trace.stages.length} output=${output}\n`);
}
